export default function UserGuideModal({ onClose }) {
  const { t } = useLanguage()
  const [open, setOpen] = useState('flow')   // หัวข้อที่กางอยู่ — เปิดทีละหัวข้อ จะได้ไม่ต้องเลื่อนยาว

  useEffect(() => {
    const onKey = (e) => { if (e.key === 'Escape') onClose() }
    window.addEventListener('keydown', onKey)
    return () => window.removeEventListener('keydown', onKey)
  }, [onClose])

  return (
    <div className="modal-overlay" onMouseDown={e => { if (e.target === e.currentTarget) onClose() }}>
      <div className="modal" style={{ maxWidth: 860, height: '88vh' }}>
        <div className="modal-header">
          <div>
            <div className="modal-title">{t('คู่มือการใช้งาน')}</div>
            <div style={{ fontSize: 12, color: 'var(--text-light)', marginTop: 2 }}>
              {t('กดหัวข้อเพื่อกาง — ทุกอย่างในระบบและความสัมพันธ์ระหว่างกัน')}
            </div>
          </div>
          <button className="modal-close" onClick={onClose}>×</button>
        </div>

        <div className="modal-body" style={{ overflow: 'auto' }}>
          {SECTIONS.map(sec => {
            const isOpen = open === sec.id
            return (
              <div key={sec.id} className="card" style={{ marginBottom: 10, overflow: 'hidden' }}>
                <button type="button" onClick={() => setOpen(isOpen ? '' : sec.id)}
                  style={{
                    width: '100%', textAlign: 'left', border: 'none', cursor: 'pointer', font: 'inherit',
                    padding: '11px 14px', background: isOpen ? 'var(--navy)' : 'var(--gray-bg)',
                    color: isOpen ? '#fff' : 'var(--navy)', fontWeight: 600, fontSize: 13,
                    display: 'flex', alignItems: 'center', gap: 8,
                  }}>
                  <span style={{ flex: 1 }}>{t(sec.title)}</span>
                  <span style={{ fontSize: 11, opacity: .8 }}>{isOpen ? '▲' : '▼'}</span>
                </button>

                {isOpen && (
                  <div style={{ padding: '12px 14px', fontSize: 12.5, lineHeight: 1.75 }}>
                    {sec.intro && <div style={{ marginBottom: 10, color: 'var(--text-light)' }}>{t(sec.intro)}</div>}

                    {sec.flow && (
                      <div style={{ marginBottom: 10 }}>
                        {FLOW.map((f, i) => (
                          <div key={f.n} style={{ display: 'flex', gap: 10, alignItems: 'flex-start', marginBottom: 8 }}>
                            <span style={{
                              flexShrink: 0, width: 22, height: 22, borderRadius: '50%', background: 'var(--navy)',
                              color: '#fff', fontSize: 11, fontWeight: 700, display: 'flex', alignItems: 'center', justifyContent: 'center',
                            }}>{f.n}</span>
                            <div style={{ minWidth: 0 }}>
                              <div style={{ fontWeight: 600, color: 'var(--navy)' }}>
                                {t(f.name)}{i < FLOW.length - 1 && <span style={{ color: 'var(--text-light)', fontWeight: 400 }}> →</span>}
                              </div>
                              <div style={{ color: 'var(--text)' }}>{t(f.what)}</div>
                            </div>
                          </div>
                        ))}
                      </div>
                    )}

                    {sec.steps && (
                      <ol style={{ margin: '0 0 10px', paddingLeft: 20 }}>
                        {sec.steps.map((st, i) => <li key={i} style={{ marginBottom: 3 }}>{t(st)}</li>)}
                      </ol>
                    )}

                    {sec.rows && (
                      <div className="table-wrap" style={{ marginBottom: 10 }}>
                        <table>
                          <tbody>
                            {sec.rows.map((r, i) => (
                              <tr key={i}>
                                <td className="col-left" style={{ fontWeight: 600, color: 'var(--navy)', whiteSpace: 'nowrap', verticalAlign: 'top' }}>{t(r[0])}</td>
                                <td className="col-left" style={{ verticalAlign: 'top' }}>{t(r[1])}</td>
                                <td className="col-left" style={{ color: 'var(--text-light)', verticalAlign: 'top' }}>{t(r[2])}</td>
                              </tr>
                            ))}
                          </tbody>
                        </table>
                      </div>
                    )}

                    {sec.notes?.length > 0 && (
                      <ul style={{ margin: 0, paddingLeft: 18 }}>
                        {sec.notes.map((n, i) => <li key={i} style={{ marginBottom: 4 }}>{t(n)}</li>)}
                      </ul>
                    )}
                  </div>
                )}
              </div>
            )
          })}

          <div style={{ fontSize: 11, color: 'var(--text-light)', textAlign: 'center', padding: '6px 0 2px' }}>
            {t('ถ้าเจอจุดที่คู่มือไม่ตรงกับระบบจริง แจ้งได้เลย')}
          </div>
        </div>

        <div className="modal-footer">
          <button className="btn btn-primary" onClick={onClose}>{t('ปิด')}</button>
        </div>
      </div>
    </div>
  )
}
